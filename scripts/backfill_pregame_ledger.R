# ============================================
# Backfill the pregame forecast ledger for weeks that predate it
# ============================================
# grade_week.R grades only from data/pregame_snapshots/<season>-wkNN.csv, and
# refuses to regrade with the current bundle (which trains on the current
# season). The ledger started at 2026 week 5, so weeks 3-4 could never be
# graded and export_games_result.R failed every run from 2026-10-08.
#
# This writes those weeks from the archived pre-game previews
# (website/public/data/weekly/<s>-wkNN/games_preview.json). Before writing,
# each archive was checked NOT to have been regenerated by a bundle that saw
# the result: its numbers differ from the current (season-trained) bundle's.
#
# Rows are tagged provenance = "backfill_preview_archive" and keep the archive
# file's REAL write time as snapshot_at, even where that falls after kickoff.
# read_frozen_pregame() accepts the tag by name; no timestamp is forged.
#
# EXCLUDED, decided 2026-10-09: 2026_03_ATL_GB (Thu 2026-09-24). Its archived
# line was written by the 2026-09-27 09:07 retrain, which had trained on that
# game. No honest pregame forecast survives, so it is recorded as
# provenance = "excluded" and is deliberately ungraded.
#
# Fields the archive does not carry are filled as follows (documented, not
# reconstructed): odds / implied probs from game_w_features (closing);
# cover_prob_home from the current bundle's sigma; EV calibration from the
# current bundle. availability_ok = NA, so no settled bets are replayed — the
# archived bet cards for both weeks showed 0 bets, so nothing is lost.
#
# WEEKS 1-2 ADDED, decided 2026-10-24. Archives written 2026-09-10 13:31 PDT
# (wk1; after only the Wed 09-09 opener) and 2026-09-21 00:00 (wk2). No bundle
# saw a 2026 game before the 2026-09-27 retrain: the scheduled retrains of
# 09-10/16/17 were skipped (locked) and 09-11/18 died on data load before
# fitting; ensemble_pre_feature_audit_2026-09-27.rds (mtime 09-20 22:02) is the
# 09-07 fit (metadata: trained 09-07, seasons 2008-2025, 4,897 games) with only
# ev_calibration added. The 09-27 bundle's 4,930 = 4,897 + wk1-2 (32) + ATL_GB.
# The Sep graded_2026_wk0{1,2}.csv files are NOT used (wk1's differs from its
# archive by up to 2.45 pts).
#
# Refuses to overwrite an existing ledger. Usage:
#   Rscript scripts/backfill_pregame_ledger.R            # 2026 weeks 1-4 (3-4 already exist)
# ============================================

source("~/Projects/R/nfl_predictor/ensemble_lib.R")
source(file.path(PROJECT_DIR, "R/lib/pregame_snapshot.R"))
suppressPackageStartupMessages(library(jsonlite))

SEASON   <- 2026L
WEEKS    <- 1:4
EXCLUDED <- c("2026_03_ATL_GB")

bundle <- readRDS(file.path(MODELS_DIR, "ensemble_latest.rds"))
cal    <- ev_calibration_from_bundle(bundle)
sigma  <- bundle$sigma
gwf    <- read.csv(file.path(DATA_DIR, "game_w_features.csv"), stringsAsFactors = FALSE)

for (wk in WEEKS) {
  out_path <- pregame_snapshot_path(DATA_DIR, SEASON, wk)
  if (file.exists(out_path)) {
    cat(sprintf("week %d: ledger already exists, refusing to overwrite %s\n", wk, out_path))
    next
  }
  arch_path <- file.path(PROJECT_DIR, "website", "public", "data", "weekly",
                         sprintf("%d-wk%02d", SEASON, wk), "games_preview.json")
  arch <- fromJSON(arch_path)$games
  arch_written <- file.info(arch_path)$mtime
  games <- gwf[gwf$season == SEASON & gwf$week == wk, ]
  stopifnot(nrow(games) > 0, setequal(games$game_id, arch$game_id))

  kickoff <- as.POSIXct(paste(games$gameday, games$gametime), tz = "America/New_York")
  ctx <- data.frame(game_id = games$game_id,
                    kickoff_at = format(kickoff, "%Y-%m-%dT%H:%M:%SZ", tz = "UTC"),
                    kickoff_epoch = as.numeric(kickoff),
                    home_moneyline = games$home_moneyline, away_moneyline = games$away_moneyline,
                    home_spread_odds = games$home_spread_odds, away_spread_odds = games$away_spread_odds,
                    impl_prob_home = games$impl_prob_home, impl_prob_away = games$impl_prob_away)

  rows <- arch %>%
    transmute(game_id, home_team, away_team,
              spread_line = as.numeric(spread_line), total_line = as.numeric(total_line),
              nfl_predictor_line = as.numeric(pred_margin),
              pred_win_pct = as.numeric(pred_win_home)) %>%
    left_join(ctx, by = "game_id") %>%
    mutate(snapshot_at = format(arch_written, "%Y-%m-%dT%H:%M:%SZ", tz = "UTC"),
           snapshot_epoch = as.numeric(arch_written),
           season = SEASON, week = as.integer(wk),
           line_diff = nfl_predictor_line - spread_line,
           cover_prob_home = pnorm(line_diff / sigma),
           availability_ok = NA, availability_reason = "backfilled; availability not recorded pregame",
           availability_checked_at = NA_character_,
           ev_cal_intercept = cal$intercept, ev_cal_slope = cal$slope,
           provenance = if_else(game_id %in% EXCLUDED, "excluded", "backfill_preview_archive")) %>%
    mutate(across(c(nfl_predictor_line, line_diff, pred_win_pct, cover_prob_home),
                  ~ if_else(provenance == "excluded", NA_real_, .x))) %>%
    select(snapshot_at, snapshot_epoch, kickoff_at, kickoff_epoch, game_id, season, week,
           home_team, away_team, spread_line, total_line, home_moneyline, away_moneyline,
           home_spread_odds, away_spread_odds, impl_prob_home, impl_prob_away,
           nfl_predictor_line, line_diff, pred_win_pct, cover_prob_home,
           availability_ok, availability_reason, availability_checked_at,
           ev_cal_intercept, ev_cal_slope, provenance)

  readr::write_csv(rows, out_path)
  mirror <- file.path(PROJECT_DIR, "website", "public", "data", "pregame_snapshots")
  dir.create(mirror, recursive = TRUE, showWarnings = FALSE)
  file.copy(out_path, file.path(mirror, basename(out_path)), overwrite = TRUE)
  cat(sprintf("week %d: wrote %d rows (%d backfilled, %d excluded) -> %s\n", wk, nrow(rows),
              sum(rows$provenance == "backfill_preview_archive"),
              sum(rows$provenance == "excluded"), out_path))
}
